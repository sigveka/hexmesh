"""
What hexmesh changes in gmsh's mesh (decision 0046 rule 5, task 0123):
every fitting's corrections recorded, "none" included, and a notice for
elements hexmesh writes.
"""

import json
import warnings

import gmsh
import numpy as np
import pytest

from hexmesh import HexmeshNotice, Session
from hexmesh.agent import cli
from hexmesh.assembly import Assembly, Bend, Straight
from hexmesh.core.spec import PipeSpec
from hexmesh.examples.fittings import junction_walls, tee

KEYS = {"fitting", "type", "wall_projection", "second_order_arc_nodes", "second_order_wall_nodes",
        "elements_written"}


@pytest.mark.parametrize("order", [1, 2])
def test_every_fitting_is_recorded_and_matches_projection_report(order):
    build = junction_walls.build if order == 1 else tee.build
    with Session("corrections"), warnings.catch_warnings():
        warnings.simplefilter("ignore")
        asm = build()
        asm.mesh(order=order)
        report = asm.check_quality()
    assert set(asm.corrections) == {e.name for e in asm.edges}
    assert report.corrections == asm.corrections
    for name, c in asm.corrections.items():
        assert set(c) == KEYS and c["elements_written"] == 0
        proj = asm.projection_report.get(name)
        if proj is None:
            assert c["wall_projection"] == "none"
            continue
        r = c["wall_projection"]
        assert r["nodes"] > 0
        assert r["largest_move"] == pytest.approx(proj["move"], rel=1e-12)
        assert r["largest_move_radii"] == pytest.approx(proj["ratio"], rel=1e-12)
        assert 0 < r["largest_move_radii"] < r["largest_move_edges"]
        placed = c["second_order_wall_nodes"]
        assert (placed == "none") == (order == 1)
    assert "What hexmesh changed in gmsh's mesh" in str(report)
    assert "none" in str(report)


def _straight():
    asm = Assembly(PipeSpec(nang=8).core("fluid", radius=0.05, nrad=3),
                   direction=[1, 0, 0], up=[0, 0, 1])
    asm.add(Straight(0.2, n_layers=4))
    return asm


def test_a_fitting_that_writes_its_elements_gives_a_notice_not_a_warning(monkeypatch):
    """The mechanism for task 0124, with a private stub: nothing sets the
    flag yet."""
    asm = _straight()
    stub = asm.edges[0].fitting
    monkeypatch.setattr(type(stub), "written_elements", True, raising=False)
    with warnings.catch_warnings():
        warnings.simplefilter("error")             # a notice is not a warning
        asm.validate()
    assert [n.code for n in asm.notices] == ["elements_written_by_hexmesh"]
    n = asm.notices[0]
    assert isinstance(n, HexmeshNotice) and not isinstance(n, Warning)
    assert n.value == asm.cell_count()
    assert f"{asm.cell_count()} elements written by hexmesh, not generated by gmsh" in str(n)
    with Session("corrections-stub"):
        asm.mesh()
        c = asm.corrections[asm.edges[0].name]
        report = str(asm.check_quality())
    assert c["elements_written"] == asm.cell_count()
    assert "elements written by hexmesh, not generated by gmsh" in report


def test_no_fitting_writes_its_elements():
    asm = _straight()
    asm.validate()
    assert asm.notices == []


def test_the_cli_reports_notices_and_corrections(tmp_path, capsys):
    asm = _straight()
    net = tmp_path / "net.json"
    asm.save(net)
    assert cli.main(["validate", str(net)]) == 0
    assert json.loads(capsys.readouterr().out)["result"]["notices"] == []
    assert cli.main(["build", str(net), "--out", str(tmp_path / "m.msh")]) == 0
    out = json.loads(capsys.readouterr().out)["result"]
    assert set(out["corrections"]) == {e.name for e in asm.edges}
    assert all(c["wall_projection"] == "none" for c in out["corrections"].values())


def _bend():
    asm = Assembly(PipeSpec(nang=8).core("fluid", radius=0.05, nrad=3),
                   direction=[1, 0, 0], up=[0, 0, 1])
    asm.add(Straight(0.1, n_layers=2))
    asm.add(Bend(0.15, 90, n_layers=6))
    asm.add(Straight(0.1, n_layers=2))
    return asm


def _nodes(order, monkeypatch=None):
    """Every node's position after ``mesh(order=order)``, and the record."""
    with Session("corrections-bend"), warnings.catch_warnings():
        warnings.simplefilter("ignore")
        asm = _bend()
        asm.mesh(order=order)
        tags, x, _ = gmsh.model.mesh.getNodes()
        return dict(zip(tags.astype(int).tolist(), x.reshape(-1, 3))), asm


def test_a_bend_at_order_2_records_its_arc_placement(monkeypatch):
    """Task 0130: the high-order nodes a bend places on its arcs are
    recorded; the largest move equals the largest displacement against
    the same mesh without the placement (gmsh's straight-edge nodes)."""
    placed, asm = _nodes(2)
    bend, *straights = [asm.edges[1].name, asm.edges[0].name, asm.edges[2].name]
    r = asm.corrections[bend]["second_order_arc_nodes"]
    assert r != "none" and r["nodes"] > 0
    assert 0 < r["largest_move_radii"] < r["largest_move_edges"] < 1
    for s in straights:
        assert asm.corrections[s]["second_order_arc_nodes"] == "none"
    assert asm.corrections[bend]["second_order_wall_nodes"] == "none"   # no projector here
    monkeypatch.setattr(Assembly, "_revolve_high_order",
                        lambda self, e, arc: (np.zeros(0), np.zeros(0), np.zeros(0)))
    gmshs, _ = _nodes(2)
    assert placed.keys() == gmshs.keys()
    moves = np.array([np.linalg.norm(placed[n] - gmshs[n]) for n in placed])
    assert r["largest_move"] == pytest.approx(moves.max(), rel=1e-12)
    assert r["nodes"] == int((moves / 0.05 > 1e-9).sum())


def test_a_bend_at_order_1_records_no_arc_placement():
    _, asm = _nodes(1)
    assert all(c["second_order_arc_nodes"] == "none" for c in asm.corrections.values())
