class _Unregistered(Straight):
    """A fitting ``to_dict`` has no type for."""


def test_unserialisable_assembly_still_writes(gmsh_session, tmp_path, recwarn):
    asm = Assembly(PipeSpec(nang=4).core("fluid", radius=0.01, nrad=1),
                   position=[0, 0, 0], direction=[1, 0, 0], up=[0, 0, 1])
    asm.add(_Unregistered(0.05, n_layers=2))
    p = tmp_path / "pipe.msh"
    asm.write(str(p))
    block = _block(p.read_bytes()).decode("ascii")
    assert "\nrecipe: not serialisable (cannot serialise fitting type _Unregistered)\n" in block
    assert msh_comments.BEGIN not in block
    assert read_recipe(p) is None
    assert not [w for w in recwarn if "serialis" in str(w.message)]


# --- round trip: every example, both writers -----------------------------------

@pytest.mark.parametrize("name", ALL)
def test_example_round_trip_is_byte_identical(name, tmp_path, monkeypatch):
    """write → from_msh → write gives the same bytes, for ``write`` and for
    ``write_openfoam``."""
    monkeypatch.chdir(tmp_path)
    stem = name.split(".")[-1]
    with contextlib.redirect_stdout(io.StringIO()):
        importlib.import_module(f"hexmesh.examples.{name}").main()
    first = tmp_path / f"{stem}.msh"
    wbf = _walls_by_fitting(first)
    with Session("again"):
        Assembly.from_msh(first).write(str(tmp_path / "again.msh"), walls_by_fitting=wbf)
    assert (tmp_path / "again.msh").read_bytes() == first.read_bytes()
    with Session("foam1"):
        Assembly.from_msh(first).write_openfoam(tmp_path / "foam1.msh", walls_by_fitting=wbf)
    with Session("foam2"):
        Assembly.from_msh(tmp_path / "foam1.msh").write_openfoam(tmp_path / "foam2.msh",
                                                                  walls_by_fitting=wbf)
    assert (tmp_path / "foam2.msh").read_bytes() == (tmp_path / "foam1.msh").read_bytes()


