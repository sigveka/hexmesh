def _have(runner: str) -> bool:
    if runner == "native":
        return of.OPENFOAM_RC.exists()
    return shutil.which("docker") is not None and subprocess.run(
        ["docker", "image", "inspect", runner[len("docker:"):]], capture_output=True).returncode == 0


@pytest.fixture
def restore_runner():
    before = of.runner()
    yield
    of.set_runner(before)


@pytest.mark.openfoam
@pytest.mark.parametrize("runner", ["native", of.V2406])
def test_gmshToFoam_ignores_the_block(runner, tmp_path, restore_runner):
    if not _have(runner):
        pytest.skip(f"no OpenFOAM for runner {runner}")
    of.set_runner(runner)
    _write(tmp_path / "on.msh", openfoam=True)
    _write(tmp_path / "off.msh", openfoam=True, provenance=False)
    meshes = {}
    for which in ("on", "off"):
        case = tmp_path / f"case_{which}"
        (case / "system").mkdir(parents=True)
        (case / "system" / "controlDict").write_bytes(
            (of.header("dictionary", "controlDict", "system") +
             "application none;\nstartFrom startTime;\nstartTime 0;\nstopAt endTime;\n"
             "endTime 1;\ndeltaT 1;\nwriteControl timeStep;\nwriteInterval 1;\n").encode("utf-8"))
        of.foam(f"gmshToFoam {tmp_path / (which + '.msh')}", case, "log.gmshToFoam",
                mounts=[tmp_path])                  # Docker: the .msh is outside the case
        poly = case / "constant" / "polyMesh"
        meshes[which] = {f.name: f.read_bytes() for f in sorted(poly.iterdir()) if f.is_file()}
    assert meshes["on"] == meshes["off"] and "points" in meshes["on"]
