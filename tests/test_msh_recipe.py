"""
The ``.msh`` recipe block (decision 0038; task 0091): written by
``Assembly.write`` and ``write_openfoam``, read back by ``read_recipe`` and
``Assembly.from_msh``, kept by gmsh re-saves and skipped by ``gmshToFoam``.
"""

import contextlib
import importlib
import io
import re
import shutil
import subprocess
from pathlib import Path

import gmsh
import pytest

from hexmesh import Assembly, Bend, PipeSpec, Session, Straight
from hexmesh.examples import ALL
from hexmesh.io import read_recipe
from hexmesh.io.writers import msh_comments
from hexmesh.study import openfoam as of

ROOT = Path(__file__).resolve().parents[1]


def _pipe():
    spec = PipeSpec(nang=4).core("fluid", radius=0.01, nrad=2).shell("steel", dR=0.002, nrad=1)
    asm = Assembly(spec, position=[0, 0, 0], direction=[1, 0, 0], up=[0, 0, 1])
    asm.add(Straight(0.05, n_layers=2))
    asm.add(Bend(0.04, 90, n_layers=4))
    return asm


def _block(data: bytes) -> bytes:
    return data[data.index(b"$Comments\n"):data.index(b"$EndComments\n") + len(b"$EndComments\n")]


def _without_block(data: bytes) -> bytes:
    return data.replace(_block(data), b"")


def _walls_by_fitting(path) -> bool:
    m = re.search(rb"^write: .*walls_by_fitting=(\w+)$", Path(path).read_bytes(), re.M)
    return m.group(1) == b"True"


