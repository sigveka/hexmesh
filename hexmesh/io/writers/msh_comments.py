"""
The ``$Comments`` block hexmesh writes into a ``.msh`` (decision 0038;
task 0091): the logo, a "generated by" line, the write options and the
recipe, so the mesh says how to rebuild itself::

    $Comments
    <the logo>
    generated by hexmesh 0.4.0 (gmsh 4.12.1, MSH 4.1 ASCII)
    write: write dim=3 walls_by_fitting=False
    hexmesh-recipe-begin
    {"format":"hexmesh.assembly",...}     <- compact JSON, 200 characters a line
    hexmesh-recipe-end
    $EndComments

It goes on the line after ``$EndMeshFormat``.  In a binary file gmsh writes
the endianness marker before that line, so the rule is the same for ASCII
and binary (docs/integrations/gmsh.md).  gmsh and ``gmshToFoam`` skip the
block; gmsh keeps it on re-save but moves it and breaks lines longer than
255 characters, so :func:`read_recipe` joins the lines between the
markers, wherever the block is.  Readers ignore lines they don't know, so
later lines can be added without a format change.

A leaf (DESIGN §3.1): plain dicts and strings, nothing about assemblies.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from ...errors import ReaderError

BEGIN, END = "hexmesh-recipe-begin", "hexmesh-recipe-end"
WRAP = 200                  # recipe characters per line (gmsh re-wraps at 255)

#: docs/ascii-logo.txt, shipped with the package (a test keeps them equal)
LOGO_LINES = (
    '       _.-------._',
    "   .-''     |     ''-.",
    " .'  \\      |      /  '.     _                                         _",
    '/     +-----+-----+     \\   | |__   ___  __  __  _ __ ___   ___  ___  | |__',
    "|     |     |     |     |   | '_ \\ / _ \\ \\ \\/ / | '_ ` _ \\ / _ \\/ __| | '_ \\",
    '|-----+-----+-----+-----|   | | | |  __/  >  <  | | | | | |  __/\\__ \\ | | | |',
    '|     |     |     |     |   |_| |_|\\___| /_/\\_\\ |_| |_| |_|\\___||___/ |_| |_|',
    '\\     +-----+-----+     /',
    " '.  /      |      \\  .'    structured all-hex meshes for pipe networks",
    "   '-..     |     ..-'",
    "       '---------'",
)


def msh_format(path) -> tuple[str, bool]:
    """(version, binary) from the file's ``$MeshFormat`` header."""
    with open(path, "rb") as f:
        if f.readline().strip() != b"$MeshFormat":
            raise ReaderError(f"{path}: not a .msh file (no $MeshFormat header)",
                              code="msh_format_invalid", where={"source": {"file": str(path)}})
        version, file_type, _ = f.readline().split()
    return version.decode(), file_type == b"1"


def block(generator: str, write: str, recipe: dict | None, *, tool: str,
          msh: tuple[str, bool], error: str | None = None) -> list[str]:
    """The block's lines.  *generator* is e.g. ``"hexmesh 0.4.0"``, *tool*
    ``"gmsh 4.12.1"``, *msh* :func:`msh_format`'s result, *write* the
    write-options text.  Without *recipe*, *error* says why."""
    version, binary = msh
    lines = ["$Comments", *LOGO_LINES,
             f"generated by {generator} ({tool}, MSH {version} {'binary' if binary else 'ASCII'})",
             f"write: {write}"]
    if recipe is None:
        lines.append(f"recipe: not serialisable ({error})")
    else:
        # "$" only occurs inside JSON strings; escaped, no wrapped line can
        # start with it and end the block early
        text = json.dumps(recipe, separators=(",", ":"), ensure_ascii=True).replace("$", "\\u0024")
        lines += [BEGIN, *(text[i:i + WRAP] for i in range(0, len(text), WRAP)), END]
    for line in lines[1:]:
        if line.startswith("$") or "\n" in line:
            raise ValueError(f"$Comments line would end the block: {line[:60]!r}")
    return lines + ["$EndComments"]


def to_lf(path) -> None:
    """Rewrite an ASCII ``.msh`` with ``\\n`` line endings.  gmsh on
    Windows writes ``\\r\\n`` (C text mode; docs/integrations/gmsh.md);
    gmshToFoam reads the file, so it is LF on every platform (decision
    0039), and byte-identical to Linux's.  Binary files are left alone:
    gmsh writes them in binary mode, and their data may hold the bytes."""
    if msh_format(path)[1]:
        return
    p = Path(path)
    data = p.read_bytes()
    if b"\r\n" in data:
        p.write_bytes(data.replace(b"\r\n", b"\n"))


def insert(path, lines: list[str]) -> None:
    """Insert the block right after ``$EndMeshFormat`` in the file at
    *path* (ASCII or binary), with the file's own line ending: gmsh on
    Windows writes ASCII files with ``\\r\\n`` (docs/integrations/gmsh.md)."""
    p = Path(path)
    data = p.read_bytes()
    m = re.search(rb"^\$EndMeshFormat(\r?\n)", data, re.M)
    if m is None:
        raise ReaderError(f"{path}: no $EndMeshFormat",
                          code="msh_format_invalid", where={"source": {"file": str(path)}})
    eol = m.group(1).decode("ascii")
    i = m.end()
    p.write_bytes(data[:i] + "".join(f"{l}{eol}" for l in lines).encode("ascii") + data[i:])


def read_recipe(path) -> dict | None:
    """The recipe in the file's hexmesh ``$Comments`` block, or None when
    there is no block or no recipe.  The lines between the markers are
    joined (a gmsh re-save breaks them) and parsed as JSON.  The file is
    read in binary, line by line, only up to the block's end."""
    parts, in_block, in_recipe = [], False, False
    with open(path, "rb") as f:
        for raw in f:
            line = raw.rstrip(b"\r\n")
            if not in_block:
                in_block = line == b"$Comments"
                continue
            if line == b"$EndComments":
                if parts:
                    break
                in_block = False            # someone else's block: keep looking
                continue
            if line == BEGIN.encode():
                in_recipe = True
            elif line == END.encode():
                in_recipe = False
            elif in_recipe:
                parts.append(line.decode("ascii"))
    return json.loads("".join(parts)) if parts else None
